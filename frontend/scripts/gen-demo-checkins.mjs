// Renders assets-src/demo-checkins/{before,after}.svg -> public/demo/checkins/{before,after}[@2x].webp
// and writes lib/fit/demoPhotos.ts (1x base64). Run: node scripts/gen-demo-checkins.mjs
import { readFile, writeFile, mkdir } from "node:fs/promises";
import sharp from "sharp";

const frame = (body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 480 640" width="480" height="640">
<defs><linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#eef1f4"/><stop offset="1" stop-color="#d5dae0"/></linearGradient>
<radialGradient id="glow" cx="0.5" cy="0.45" r="0.6"><stop offset="0" stop-color="#fff" stop-opacity="0.7"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient></defs>
<rect width="480" height="640" fill="url(#bg)"/><rect width="480" height="640" fill="url(#glow)"/>
<rect x="0" y="588" width="480" height="52" fill="#c3c9d0"/>
<ellipse cx="250" cy="590" rx="95" ry="9" fill="#000" opacity="0.14"/>
${body}</svg>`;

const SKIN = "#b9a79a", TOP = "#3f8f8a", SHORTS = "#2f3b4d", SHOE = "#f4f4f4";
const common = `
<g stroke-linecap="round" stroke-linejoin="round" fill="none">
 <path d="M240 372 L246 480 L240 568" stroke="${SKIN}" stroke-width="30"/>
 <path d="M240 372 L246 440" stroke="${SHORTS}" stroke-width="46"/>
</g>
<path d="M226 566 h70 a12 12 0 0 1 12 12 v6 h-92 z" fill="${SHOE}" stroke="#aab" stroke-width="2"/>`;

const after = frame(`${common}
<g stroke-linecap="round" stroke-linejoin="round">
 <path d="M258 236 L262 306 L268 372" stroke="${SKIN}" stroke-width="20" fill="none"/>
 <rect x="236" y="168" width="20" height="44" rx="9" fill="${SKIN}"/>
 <ellipse cx="248" cy="148" rx="30" ry="33" fill="${SKIN}"/>
 <path d="M218 376 C216 330 224 300 226 262 C224 236 228 214 240 206 L268 206 C284 214 288 238 280 262 C268 282 262 300 264 326 C268 350 270 362 270 376 Z" fill="${TOP}"/>
 <path d="M218 360 L270 360 L274 400 L216 400 Z" fill="${SHORTS}"/>
 <path d="M262 214 C272 214 276 236 272 270 L276 286" stroke="${TOP}" stroke-width="22" fill="none" opacity="0"/>
 <path d="M244 222 L246 302 L252 372" stroke="${SKIN}" stroke-width="20" fill="none"/>
 <path d="M240 210 L246 232" stroke="${TOP}" stroke-width="26" fill="none"/>
</g>`);

const before = frame(`${common}
<g stroke-linecap="round" stroke-linejoin="round">
 <path d="M296 190 L270 214" stroke="${SKIN}" stroke-width="20" fill="none"/>
 <ellipse cx="300" cy="170" rx="30" ry="33" fill="${SKIN}"/>
 <path d="M218 376 C206 340 200 300 198 268 C196 232 226 206 262 208 C282 212 282 236 276 262 C270 282 276 296 292 322 C304 344 296 366 274 376 Z" fill="${TOP}"/>
 <path d="M218 362 L286 360 L290 400 L216 400 Z" fill="${SHORTS}"/>
 <path d="M262 228 L276 306 L292 370" stroke="${SKIN}" stroke-width="22" fill="none"/>
 <path d="M254 214 L266 238" stroke="${TOP}" stroke-width="28" fill="none"/>
</g>`);

await mkdir("assets-src/demo-checkins", { recursive: true });
await mkdir("public/demo/checkins", { recursive: true });
const out = {};
for (const [name, svg] of [["before", before], ["after", after]]) {
	await writeFile(`assets-src/demo-checkins/${name}.svg`, svg);
	const buf = Buffer.from(svg);
	await sharp(buf, { density: 144 }).resize(960, 1280).webp({ quality: 80 }).toFile(`public/demo/checkins/${name}@2x.webp`);
	await sharp(buf, { density: 72 }).resize(480, 640).webp({ quality: 80 }).toFile(`public/demo/checkins/${name}.webp`);
	out[name] = (await readFile(`public/demo/checkins/${name}.webp`)).toString("base64");
}
await writeFile("lib/fit/demoPhotos.ts", `// Generated by scripts/gen-demo-checkins.mjs - synthetic illustrated mannequins, not real people.\nexport const DEMO_PHOTO_BEFORE = "data:image/webp;base64,${out.before}";\nexport const DEMO_PHOTO_AFTER = "data:image/webp;base64,${out.after}";\n`);
console.log("ok");
